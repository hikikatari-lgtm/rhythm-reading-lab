// Rests
const RQ: Tok = { d: 1, rest: true };
// Dotted
const DH: Tok = { d: 2, dot: true }; // dotted half = 3 beats
const DQ: Tok = { d: 1, dot: true }; // dotted quarter = 1.5 beats

const BPM: Record<number, number> = { 1: 80, 2: 88, 3: 96, 4: 100, 5: 92, 6: 104 };

function q(
  level: number,
  num: number,
  question: string,
  choices: Tok[][],
  correctIndex: number,
  explanation: string,
  songName?: string
): RhythmQuestion {
  const built = choices.map(seq);
  return {
    id: `l${level}-q${String(num).padStart(2, "0")}`,
    level,
    question,
    bpm: BPM[level],
    timeSignature: [4, 4],
    rhythm: built[correctIndex],
    choices: built.map((rhythm) => ({ rhythm })),
    correctIndex,
    explanation,
    ...(songName ? { songName } : {}),
  };
}

