import type { RhythmEvent, RhythmQuestion } from "./types";

// ---------------------------------------------------------------------------
// Authoring helpers. A "token" is a note value plus optional flags; `seq`
// lays tokens out left-to-right, auto-computing each event's beat position.
// ---------------------------------------------------------------------------

type Tok =
  | number
  | { d: number; rest?: boolean; dot?: boolean; tie?: boolean; stroke?: "down" | "up" };

function seq(tokens: Tok[]): RhythmEvent[] {
  let beat = 0;
  const out: RhythmEvent[] = [];
  for (const t of tokens) {
    const o = typeof t === "number" ? { d: t } : t;
    out.push({
      beat,
      duration: o.d,
      ...(o.rest ? { rest: true } : {}),
      ...(o.dot ? { dot: true } : {}),
      ...(o.tie ? { tie: true } : {}),
      ...(o.stroke ? { stroke: o.stroke } : {}),
    });
    beat += (o.dot ? o.d * 1.5 : o.d);
  }
  return out;
}

// Note values
const W = 4;
const H = 2;
const Q = 1;
const E = 0.5;
